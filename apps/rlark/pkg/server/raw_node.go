// RawNodeSignRequest selects an administrator-provisioned container instance.
// All UIDs and incarnation must match live state; names alone never enroll it.
type RawNodeSignRequest struct {
	Cluster     string `json:"cluster"`
	ClusterUID  string `json:"cluster_uid"`
	Namespace   string `json:"namespace"`
	Node        string `json:"node"`
	NodeUID     string `json:"node_uid"`
	Incarnation string `json:"incarnation"`
	TenantID    string `json:"tenant_id"`
	// EnrollmentID identifies a retryable issuance operation, generated by the
	// administrator. PreviousCredentialID is its compare-and-swap precondition.
	EnrollmentID         string `json:"enrollment_id"`
	PreviousCredentialID string `json:"previous_credential_id,omitempty"`
}

func (s *Server) prepareRawNodeCertificate(ctx context.Context, r *RawNodeSignRequest) (map[string]string, error) {
	if r == nil {
		return nil, errors.New("raw_node instance identity required")
	}
	if _, err := uuid.Parse(r.EnrollmentID); err != nil {
		return nil, errors.New("enrollment_id must be an administrator-generated UUID")
	}
	if r.PreviousCredentialID == r.EnrollmentID {
		return nil, errors.New("new enrollment_id required for rotation")
	}
	i := rawnode.Identity{Cluster: r.Cluster, ClusterUID: r.ClusterUID, Namespace: r.Namespace, Node: r.Node, NodeUID: r.NodeUID, Incarnation: r.Incarnation, TenantID: r.TenantID, CredentialID: r.EnrollmentID}
	if _, err := rawnode.FromMetadata(i.Metadata()); err != nil {
		return nil, err
	}
	if _, err := s.validateRawNode(ctx, i, false); err != nil {
		return nil, err
	}
	// This administrator-only rotation is durable before a key is returned. A
	// failed signing attempt may invalidate the old key and is retried explicitly.
	err := retry.RetryOnConflict(retry.DefaultRetry, func() error {
		n, err := s.validateRawNode(ctx, i, false)
		if err != nil {
			return err
		}
		current := n.Annotations[rawnode.CredentialAnnotation]
		if current == i.CredentialID {
			return nil // Lost response: reissue only this still-current identity.
		}
		if current != r.PreviousCredentialID {
			return apierrors.NewConflict(schema.GroupResource{Group: api.GroupVersion.Group, Resource: "nodes"}, i.Node, errors.New("Raw enrollment precondition changed"))
		}
		n = n.DeepCopy()
		if n.Annotations == nil {
			n.Annotations = map[string]string{}
		}
		n.Annotations[rawnode.CredentialAnnotation] = i.CredentialID
		_, err = s.rlarkClient.RlinfV1alpha1().Nodes(i.Namespace).Update(ctx, n, metav1.UpdateOptions{})
		return err
	})
	if err != nil {
		return nil, fmt.Errorf("rotate Raw node credential: %w", err)
	}
	return i.Metadata(), nil
}

func (s *Server) validateRawNode(ctx context.Context, i rawnode.Identity, credential bool) (*api.Node, error) {
	deny := func() (*api.Node, error) { return nil, errors.New("Raw node identity is not current") }
	clusters, err := s.rlarkClient.RlinfV1alpha1().Clusters().List(ctx, metav1.ListOptions{})
	if err != nil {
		return nil, err
	}
	var cluster *api.Cluster
	for j := range clusters.Items {
		c := &clusters.Items[j]
		if c.Spec.AgentNamespace != i.Namespace {
			continue
		}
		if cluster != nil {
			return deny()
		}
		cluster = c
	}
	if cluster == nil || cluster.Name != i.Cluster || string(cluster.UID) != i.ClusterUID || tenant.IDOf(cluster) != i.TenantID || !cluster.DeletionTimestamp.IsZero() {
		return deny()
	}
	node, err := s.rlarkClient.RlinfV1alpha1().Nodes(i.Namespace).Get(ctx, i.Node, metav1.GetOptions{})
	if err != nil {
		return nil, err
	}
	if string(node.UID) != i.NodeUID || tenant.IDOf(node) != i.TenantID || node.Spec.AgentType != api.AgentTypeRaw || !node.DeletionTimestamp.IsZero() || node.Status.Raw == nil || node.Status.Raw.Incarnation != i.Incarnation || (credential && node.Annotations[rawnode.CredentialAnnotation] != i.CredentialID) {
		return deny()
	}
	return node, nil
}

func (s *Server) rawNodeIdentity(c *gin.Context) (rawnode.Identity, *api.Node, bool) {
	i, err := rawnode.FromMetadata(GetCertMetaFromContext(c))
	if err != nil {
		rawDenied(c)
		return i, nil, false
	}
	n, err := s.validateRawNode(c.Request.Context(), i, true)
	if err != nil {
		rawDenied(c)
		return i, nil, false
	}
	return i, n, true
}

func (s *Server) handleRawNodeHeartbeat(c *gin.Context) {
	i, _, ok := s.rawNodeIdentity(c)
	if !ok {
		return
	}
	err := retry.RetryOnConflict(retry.DefaultRetry, func() error {
		node, err := s.validateRawNode(c.Request.Context(), i, true)
		if err != nil {
			return err
		}
		leases := s.kubeClient.CoordinationV1().Leases(i.Namespace)
		name := "node-heartbeat-" + i.Node
		lease, err := leases.Get(c.Request.Context(), name, metav1.GetOptions{})
		missing := apierrors.IsNotFound(err)
		if missing {
			lease = &coordinationv1.Lease{ObjectMeta: metav1.ObjectMeta{Name: name, Namespace: i.Namespace, OwnerReferences: []metav1.OwnerReference{*metav1.NewControllerRef(node, api.GroupVersion.WithKind("Node"))}}}
		} else if err != nil {
			return err
		} else {
			owner := metav1.GetControllerOf(lease)
			if owner == nil || owner.APIVersion != api.GroupVersion.String() || owner.Kind != "Node" || owner.Name != node.Name || owner.UID != node.UID {
				return errors.New("heartbeat Lease ownership cannot be proven")
			}
			lease = lease.DeepCopy()
		}
		now := metav1.NewMicroTime(time.Now())
		duration := int32(45)
		lease.Spec.RenewTime = &now
		lease.Spec.LeaseDurationSeconds = &duration
		holder := i.HeartbeatHolder()
		lease.Spec.HolderIdentity = &holder
		if missing {
			_, err = leases.Create(c.Request.Context(), lease, metav1.CreateOptions{})
		} else {
			_, err = leases.Update(c.Request.Context(), lease, metav1.UpdateOptions{})
		}
		return err
	})
	if err != nil {
		c.JSON(http.StatusServiceUnavailable, gin.H{"error": "Raw heartbeat unavailable"})
		return
	}
	c.Status(http.StatusNoContent)
}
